const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const elements=new Map();
const element=id=>{if(!elements.has(id)) elements.set(id,{innerHTML:'',textContent:'',style:{},querySelectorAll(){return []},addEventListener(){}});return elements.get(id)};
const ctx=vm.createContext({console,document:{getElementById:element,addEventListener(){}},localStorage:{getItem(){return null}},window:{}});
vm.runInContext(fs.readFileSync('web/app.js','utf8').split('(async function boot()')[0],ctx);
ctx.fixture=JSON.parse(fs.readFileSync('web/data/sentences.json','utf8'));
vm.runInContext('DATA=fixture;state={dialect:"egypt",progress:{}};',ctx);
const run=code=>vm.runInContext(code,ctx);
const enabled=()=>[...element('path').innerHTML.matchAll(/<button data-day="(\d+)" ([^>]*)>/g)].filter(m=>!m[2].includes('disabled')).map(m=>Number(m[1]));
run('renderPath(1,false,1)');assert.deepEqual(enabled(),[1]);
run('renderPath(1,false,15)');assert.deepEqual(enabled(),[],'future unit must remain locked');
run('progress().completedDays=[1,2,3];renderPath(4,false,1)');assert.deepEqual(enabled(),[1,2,3,4]);
assert.match(element('path').innerHTML,/id="today-start"/);
run('state.dialect="jordan";renderPath(nextDay(),false,1)');assert.deepEqual(enabled(),[1],'country progress stays separate');
run('progress().completedDays=Array.from({length:100},(_,i)=>i+1);renderPath(100,true,15)');
assert.equal(enabled().length,ctx.fixture.units.at(-1).lastDay-ctx.fixture.units.at(-1).firstDay+1);
assert.doesNotMatch(element('path').innerHTML,/id="today-start"/,'completed curriculum only offers replay');
assert.match(element('world-next').innerHTML,/전체 학습 완료/);
console.log('PASS: current day, future locks, replay, separate country progress, completed curriculum');
